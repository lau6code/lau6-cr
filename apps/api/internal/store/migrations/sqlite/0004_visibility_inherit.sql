-- lau6-cr 仓库可见性跟随项目（SQLite 方言）
--
-- 背景：仓库可见性原先只有 public/private 两个值，而"公开项目里的镜像"
-- 要匿名可拉，需要**项目与仓库都公开**。于是：
--   - 自动建仓时写死 private → 公开项目里的镜像一律匿名拉不到；
--   - 管理员想修，得挨个仓库手动改可见性。
--
-- 改法：仓库多一个 inherit_visibility 标记：
--   1 = 跟随项目（生效可见性 = 项目可见性）
--   0 = 显式设置（生效可见性 = 仓库自己的 visibility 列）
--
-- 生效可见性在 SQL 里用 CASE 解析（见 store/repo.go 的 repoSelect），
-- 权限判定、目录过滤、UI 展示拿到的是同一个值。
--
-- ⚠️ 默认值 1 = "跟随项目"：既有行全部变成继承。
--    这正是我们要的——旧行里的 private 是**自动建仓时写死的**，
--    不是谁有意收紧的。项目私有时它们的生效可见性不变（项目是硬门槛），
--    项目公开时它们跟着公开。
--
-- 想要单独收紧的，项目管理员在仓库设置里显式改成 private 即可。
ALTER TABLE repositories ADD COLUMN inherit_visibility INTEGER NOT NULL DEFAULT 1;

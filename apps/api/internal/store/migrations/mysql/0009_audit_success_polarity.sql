-- lau6-cr 审计 success 列极性修正（MySQL 方言）
--
-- 背景：审计的**写侧**把布尔取反了——success=true 存成 0、success=false 存成 1。
-- 建表默认值是 DEFAULT 1（= 成功），读侧（store.ListAudit）把它直接 Scan 进 bool，
-- 两头都按"1 = 成功"读，只有写侧是反的。
-- 后果：审计页把"登录失败"显示成 success=true、把成功显示成 false——
-- 记录本身没错，是标签反了，而看标签的人会照着标签得出相反的结论。
--
-- 写侧已在本版本修正（store/audit.go）。本迁移把**存量行**的极性翻正。
--
-- 判据：存量行全部由旧的取反写侧产生 ⇒ 存量 100% 需要翻。
-- 写侧修正与本迁移**同一个版本发布**：迁移在启动时执行（早于对外服务），
-- 那时库里还没有任何由修正后写侧产生的行 ⇒ 存量即全部，不必挑拣。
--
-- ⚠️ 若某个实例先上了修正后的写侧、之后才升到带本迁移的版本，
--    那批新行会被误翻。写侧修正与本迁移必须一起发布。
--
-- ⚠️ 重跑安全性：翻正是对合（翻两次回到原值）。
--    迁移失败会让启动中止（Migrate 失败即 os.Exit(1)），
--    服务没起来就不会有修正后写侧产生的新行；
--    重跑只会把存量行翻回迁移前的状态，不会比迁移前更坏。
--
-- success 列在三套方言里都是整型（BIGINT / INTEGER），
-- 所以 1 - success 在三个引擎上是同一句。
UPDATE audit_logs SET success = 1 - success;
